  var API = {
    locales: ['fr', 'en'],

    currentLocale: function () {
      var raw = '';
      try {
        raw = (global.NUTRI_I18N && global.NUTRI_I18N.locale) ||
          document.documentElement.lang ||
          (global.localStorage && global.localStorage.getItem('nutri_language')) || 'en';
      } catch (e) { raw = 'en'; }
      var code = String(raw).toLowerCase().split(/[-_]/)[0];
      return STRINGS[code] ? code : 'en';
    },

    t: function (key, params) {
      var locale = this.currentLocale();
      var pack = STRINGS[locale] || STRINGS.en;
      var value = pack[key];
      if (value == null) value = STRINGS.en[key];
      if (value == null) value = key;
      if (params) {
        Object.keys(params).forEach(function (k) {
          value = value.split('{' + k + '}').join(String(params[k]));
        });
      }
      return value;
    },

    /* Localise a {fr,en} object coming from the data file. */
    loc: function (obj) {
      if (obj == null) return '';
      if (typeof obj === 'string') return obj;
      var locale = this.currentLocale();
      return obj[locale] || obj.en || obj.fr || '';
    },

    has: function (key) { return !!(STRINGS[API.currentLocale()] || {})[key]; }
  };

  global.NUTRI_DEVICES_SIM_I18N = API;
